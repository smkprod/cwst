namespace ClanWarTracker.Application.DTOs;

/// <summary>
/// «Разведка гонки» — досье на каждый клан текущей недели.
///
/// Отвечает на вопрос, который глава задаёт каждый четверг и на который до сих пор
/// отвечал наугад: упираться в эту неделю или второе место уже потолок. Таблица гонки
/// показывает, кто впереди сейчас; разведка показывает, чего эти кланы стоят вообще —
/// их обычный результат, стабильность и то, идут ли они сейчас выше или ниже себя.
///
/// Соперник такого о себе не видит: данные собираются из его же публичного журнала войн.
/// </summary>
public record RaceScoutDto(
    bool IsPro,
    int WeeksAnalyzed,                  // сколько завершённых недель удалось разобрать
    List<ScoutClanDto> Clans,           // в порядке текущих мест в гонке
    string? FreeTeaser,                 // код дразнилки для Free; null — дразнить нечем
    string? RealRivalTag);              // с кем реально идёт борьба; null — не определился

/// <summary>
/// Досье на один клан. Только числа и коды — формулировки собирает фронт,
/// иначе разведка говорила бы по-русски в английском интерфейсе.
/// </summary>
public record ScoutClanDto(
    string Tag,
    string Name,
    int Position,                       // место в гонке сейчас
    bool IsOurClan,
    int CurrentFame,                    // медали за эту неделю на данный момент
    List<int> DayPoints,                // очки по завершённым дням этой недели

    // --- Из журнала войн соперника (последние недели) ---
    int WeeksTracked,                   // сколько недель нашлось на этот клан
    int AvgWeekFame,                    // средний итог недели
    int BestWeekFame,
    double AvgRank,                     // обычное место (1..5)
    int Volatility,                     // 0..100: разброс результатов, больше — непредсказуемее
    // Дисциплина соперника меряется колодами, а не тем, доплыл ли он до финиша:
    // финиш зависит и от соперников по гонке, а отыгранные колоды — только от него.
    double AvgDecksPerPlayer,           // сколько колод из 16 в среднем отыгрывает участник
    int AvgParticipants,                // сколько человек реально воюет

    // --- Как они идут сейчас относительно себя обычного ---
    int PaceVsUsualPercent,             // +12 = на 12% выше своего обычного темпа; 0 — не посчитать
    bool FadesLate);                    // проседают во второй половине недели (по журналу дней)
