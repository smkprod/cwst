namespace ClanWarTracker.Application.DTOs;

/// <summary>
/// «Дисциплина клана» — кто подводит и кого приходится тянуть.
///
/// Пришло на смену «шансу победы»: тот показывал число, с которым нечего делать
/// (проценты меняются сами по себе, и повлиять на них глава не мог). Здесь наоборот —
/// каждая строка называет конкретного человека и конкретное действие: поговорить,
/// напомнить заранее, попрощаться.
///
/// Все подписи собирает фронт: сервер отдаёт только числа, иначе карточка говорила бы
/// по-русски в английском и украинском интерфейсе.
/// </summary>
public record ClanDisciplineDto(
    int WeeksAnalyzed,                     // сколько завершённых недель попало в расчёт
    List<DisciplinePlayerDto> Skippers,    // кто чаще всех недоигрывает войну
    List<DisciplinePlayerDto> Nudged,      // кого чаще всех приходится пинать
    List<DisciplinePlayerDto> LastMinute); // кто отыгрывает у самого дедлайна

/// <summary>Один игрок в карточке дисциплины. Списки сортируются на сервере.</summary>
public record DisciplinePlayerDto(
    string PlayerTag,
    string Name,
    int MissedDecks,          // недоигранные военные колоды за учтённые недели
    int MissedWeeks,          // недель в составе, где не сыграл ни одной атаки
    int WeeksTracked,         // сколько недель игрок вообще был в составе
    int NudgeCount,           // сколько раз бот его пинал (ЛС или тег в чате)
    int LastMinuteBattles,    // бои, сыгранные в последний час перед концом дня
    int TotalBattles,         // всего боёв в журнале за период (знаменатель для процента)
    double AvgHoursBeforeEnd);// в среднем за сколько часов до конца дня отыгрывает
