namespace ClanWarTracker.Domain.Enums;

/// <summary>
/// Что именно разрешено человеку с доступом к панели.
///
/// Флагами, а не отдельной ролью на каждый набор: ролей пришлось бы заводить по
/// одной на каждое сочетание («смотрит и рассылает», «смотрит и выдаёт тарифы»),
/// и список рос бы быстрее, чем к нему привыкают.
///
/// Значения явные и не переиспользуются: они лежат в базе числом, и сдвиг любого
/// из них молча переназначил бы права всем, кому они уже выданы.
/// </summary>
[Flags]
public enum ServicePermission
{
    /// <summary>Только сводка и список кланов — то, что видно каждому в панели.</summary>
    None = 0,

    /// <summary>Заходить в любой клан на просмотр.</summary>
    EnterClans = 1,

    /// <summary>Действовать внутри клана наравне с главой: пинать, менять настройки, звать.</summary>
    ManageClans = 2,

    /// <summary>Настраивать бота в любом чате, не будучи там админом.</summary>
    ChatAdmin = 4,

    /// <summary>Выдавать и снимать тарифы.</summary>
    Plans = 8,

    /// <summary>Рассылка по всем игрокам и чатам.</summary>
    Broadcast = 16,

    /// <summary>Отвязывать кланы от сервиса вместе с историей войн.</summary>
    DeleteClans = 32,

    /// <summary>Назначать и снимать модераторов. По сути — делает человека вторым владельцем.</summary>
    ManageModerators = 64,

    /// <summary>Обслуживание: пересобрать снимок мирового топа и тому подобное.</summary>
    Maintenance = 128,

    All = EnterClans | ManageClans | ChatAdmin | Plans | Broadcast
        | DeleteClans | ManageModerators | Maintenance,
}
